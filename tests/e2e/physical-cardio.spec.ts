import {expect,test} from "@playwright/test";

test.use({baseURL:process.env.LIFE_OS_E2E_URL??"http://localhost:3210",channel:process.env.LIFE_OS_E2E_CHANNEL||undefined,viewport:{width:390,height:844}});
test.beforeEach(async({page})=>{
 await page.goto("/access");
 await page.getByLabel("Lozinka").fill(process.env.LIFE_OS_E2E_PASSWORD??"life-os-disposable-smoke-password-2026");
 await page.getByRole("button",{name:"Prijavi se"}).click();
 await expect(page).toHaveURL("/");
});
test("records, edits and repeats a bike workout without carrying over results",async({page})=>{
 const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
 const title=`Kardio provera ${Date.now()}`;
 await page.goto("/activities/new");
 await page.getByRole("group",{name:"Vrsta treninga"}).getByRole("button",{name:/^Kardio/}).click();
 await page.getByRole("textbox",{name:"Naziv treninga (opciono)",exact:true}).fill(title);
 const block=page.locator("[data-block]").first();
 await expect(block.getByLabel("Vrsta kardija")).toHaveValue("stationary_bike");
 await block.getByLabel("Minuti",{exact:true}).fill("30");
 await block.getByLabel("Distanca (opciono)",{exact:false}).fill("12,5");
 await block.locator("summary").filter({hasText:"Dodatni podaci sa sprave"}).click();
 await block.getByLabel("Nivo otpora").fill("6");
 await block.getByLabel(/Prosečan puls/).fill("135");
 await block.getByLabel(/Kalorije/).fill("240");
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
 await page.screenshot({path:"/private/tmp/life-os-cardio-mobile.png",fullPage:true});
 await page.getByRole("button",{name:"Sačuvaj aktivnost",exact:true}).click();
 await expect(page).toHaveURL("/activities");
 const row=page.getByRole("listitem").filter({hasText:title});
 await expect(row).toContainText("Sobni bicikl");await expect(row).toContainText("12,5 km");
 await row.getByRole("link",{name:`Pregled treninga: ${title}`}).click();
 await expect(page.getByRole("heading",{name:title,exact:true})).toBeVisible();
 const detailUrl=page.url();
 await expect(page.getByText("Vreme kardija",{exact:true})).toBeVisible();
 await expect(page.getByText("Tempo trčanja",{exact:true})).toHaveCount(0);
 await page.getByRole("link",{name:"Izmeni",exact:true}).click();
 await expect(page.getByLabel("Minuti",{exact:true}).first()).toHaveValue("30");
 await page.getByLabel("Minuti",{exact:true}).first().fill("35");
 await page.getByRole("button",{name:"Sačuvaj aktivnost",exact:true}).click();
 await expect(page).toHaveURL(detailUrl);
 await expect(page.getByText("00:35:00",{exact:true})).toBeVisible();
 await page.getByRole("link",{name:"Ponovi trening"}).click();
 await page.getByRole("button",{name:"Učitaj trening"}).click();
 await expect(page.getByLabel("Vrsta kardija")).toHaveValue("stationary_bike");
 await expect(page.getByLabel("Minuti",{exact:true}).first()).toHaveValue("");
 await page.goto(`${detailUrl}/edit`);
 page.once("dialog",dialog=>dialog.accept());
 await page.getByRole("button",{name:"Obriši",exact:true}).click();
 await expect(page).toHaveURL("/activities");
 expect(errors).toEqual([]);
});
test("switches cardio machine fields and supports treadmill running and template goals",async({page})=>{
 await page.goto("/activities/new");
 await page.getByRole("group",{name:"Vrsta treninga"}).getByRole("button",{name:/^Kardio/}).click();
 const block=page.locator("[data-block]").first();
 await block.getByLabel("Vrsta kardija").selectOption("stepper");
 await block.locator("summary").filter({hasText:"Dodatni podaci sa sprave"}).click();
 await expect(block.getByLabel("Spratovi")).toBeVisible();await expect(block.getByLabel("Nivo otpora")).toHaveCount(0);
 await block.getByLabel("Vrsta kardija").selectOption("walking");
 await block.getByRole("combobox",{name:/^Mesto/}).selectOption("treadmill");
 await expect(block.getByLabel(/Nagib/)).toBeVisible();
 await block.getByLabel("Vrsta kardija").selectOption("other");
 await block.getByLabel("Naziv aktivnosti").fill("Aerobik");
 await page.getByRole("button",{name:"Trčanje",exact:true}).last().click();
 await page.locator("[data-block]").last().getByLabel("Mesto trčanja").selectOption("treadmill");
 await page.goto("/plans/workouts/new");
 await page.getByRole("button",{name:"Kardio",exact:true}).click();
 const template=page.locator("[data-block]").last();
 await expect(template.getByLabel("Vrsta kardija")).toHaveValue("stationary_bike");
 await expect(template.getByLabel(/Prosečan puls/)).toHaveCount(0);
 await expect(template.getByText("Trajanje (s)",{exact:true})).toBeVisible();
});
